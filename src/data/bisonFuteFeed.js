/**
 * Bison Futé feed projection — the seam between two raw DATEX II documents and
 * the compact JSON the browser is actually served.
 *
 * Lives here rather than inside `vite.config.js` for the same reason
 * `vigicruesFeed.js` and `firmsCsv.js` do: the parsing of a third-party feed is
 * the part most likely to break when that feed shifts, so it belongs somewhere
 * a unit test can point at a real captured response. The dev-server proxy
 * imports these projections; nothing in the browser bundle does.
 *
 * TWO PRODUCTS, ONE SUPPLIER
 *
 *   Événementiel-DIR — every incident, roadworks order, closure, diversion and
 *     restriction the Directions interdépartementales des routes have declared
 *     on the non-conceded national network, as DATEX II v2 `SituationPublication`.
 *   QTV-DIR — average speed and hourly flow per measurement station, as DATEX II
 *     `MeasuredDataPublication`, joined to a `refDir.csv` referential that
 *     carries each station's Lambert-93 geometry.
 *
 * Both are open, keyless, Licence Ouverte 2.0, and cover the RRN **non concédé**
 * only: the conceded motorways (the ASF/APRR/Sanef network) are NOT in here and
 * their absence is a property of the source, not a gap in this code.
 *
 * MEASURED against the live feeds on 2026-08-31:
 *   - events: 3,365,501 bytes raw / 165,296 gzipped, ETag + Last-Modified both
 *     served, republished hourly at HH:13 (the payload's own `publicationTime`
 *     matched `Last-Modified` to the second)
 *   - 286 situations holding 600 situation records — 191 points, 409 segments,
 *     and every single record carried coordinates
 *   - QTV: 1,251,866 bytes raw / 26,727 gzipped, republished every ~6 minutes;
 *     `publicationTime` 22:00, `measurementTimeDefault` 22:06, file written
 *     22:11 — so a reading is ~12 minutes old before a browser can see it,
 *     which is why the layer publishes a measurement AGE and not just a value
 *   - QTV referential: 1,206 stations, 840 with two usable endpoints, 364 with
 *     none at all, and one station id (`#MZo57.2`) present in the measurements
 *     with no referential row behind it
 *
 * Conditional GET works on all three URLs (verified 304 with `If-None-Match`),
 * which is what makes a 5-minute poll of a 3.3 MB document affordable — see the
 * proxy in `vite.config.js`.
 */

