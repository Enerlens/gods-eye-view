// A minimal XML reader
// ---------------------------------------------------------------------------

/**
 * WHY A HAND-WRITTEN PARSER and not a dependency: these are the only two XML
 * documents the app reads, they are machine-generated by one supplier against a
 * published schema, and the alternative is adding a parser to `package.json` for
 * ~90 lines of scanning. The scanner deliberately understands only what DATEX II
 * uses — elements, attributes, text, comments, CDATA and the five predefined
 * entities. It has no DTD, no namespace resolution and no entity declarations,
 * because a feed that needed any of those would be a feed this projection could
 * not trust anyway.
 *
 * Namespace PREFIXES are stripped rather than resolved. The two documents
 * disagree about them — the events publication is `ns2:`-prefixed with the
 * DATEX namespace on the prefix, QTV declares the same namespace as the default
 * — so matching on prefixed names would need two code paths for one schema.
 * Local names are unambiguous inside DATEX II, and `xsi:type` is read as the
 * attribute `type`, its own prefix stripped the same way.
 */

/** One parsed element. `text` is the concatenated direct text content. */
class XmlElement {
  constructor(name, attrs) {
    /** @type {string} Local name, prefix stripped. */
    this.name = name;
    /** @type {Record<string,string>} Attributes, prefixes stripped. */
    this.attrs = attrs;
    /** @type {XmlElement[]} */
    this.children = [];
    /** @type {string} */
    this.text = '';
  }
}

const XML_ENTITIES = Object.freeze({
  amp: '&', lt: '<', gt: '>', quot: '"', apos: "'",
});

/**
 * Decode the predefined entities and numeric character references.
 * @param {string} raw Raw text run.
 * @returns {string}
 */
export function decodeXmlText(raw) {
  if (raw.indexOf('&') === -1) return raw;
  return raw.replace(/&(#x?[0-9a-fA-F]+|[a-zA-Z]+);/g, (match, body) => {
    if (body[0] === '#') {
      const code = body[1] === 'x' || body[1] === 'X'
        ? Number.parseInt(body.slice(2), 16)
        : Number.parseInt(body.slice(1), 10);
      return Number.isFinite(code) && code >= 0 && code <= 0x10ffff
        ? String.fromCodePoint(code)
        : match;
    }
    return Object.hasOwn(XML_ENTITIES, body) ? XML_ENTITIES[body] : match;
  });
}

/** Strip a namespace prefix from a qualified name. */
function localName(qualified) {
  const colon = qualified.indexOf(':');
  return colon === -1 ? qualified : qualified.slice(colon + 1);
}

const ATTRIBUTE_PATTERN = /([^\s=/>]+)\s*=\s*("([^"]*)"|'([^']*)')/g;

/** Parse one start-tag's attribute run into a plain object. */
function parseAttributes(source) {
  const attrs = {};
  if (!source || !source.includes('=')) return attrs;
  ATTRIBUTE_PATTERN.lastIndex = 0;
  let match = ATTRIBUTE_PATTERN.exec(source);
  while (match) {
    attrs[localName(match[1])] = decodeXmlText(match[3] !== undefined ? match[3] : match[4]);
    match = ATTRIBUTE_PATTERN.exec(source);
  }
  return attrs;
}

/**
 * Parse an XML document into a tree of {@link XmlElement}.
 *
 * Tolerant by design in one direction only: unexpected content (comments,
 * processing instructions, a stray close tag) is skipped, but a document with
 * no root element throws rather than returning an empty tree that a caller
 * would report as "the feed published nothing today".
 *
 * @param {string} text Raw XML.
 * @returns {XmlElement} Root element.
 * @throws {Error} When the document holds no element at all.
 */
export function parseXml(text) {
  const source = String(text ?? '');
  const stack = [];
  let root = null;
  let cursor = 0;

  while (cursor < source.length) {
    const open = source.indexOf('<', cursor);
    if (open === -1) break;

    if (open > cursor && stack.length) {
      const run = source.slice(cursor, open);
      // Elements in these documents hold either children or text, never both,
      // so trimming here cannot swallow significant whitespace between runs.
      if (run.trim()) stack[stack.length - 1].text += decodeXmlText(run);
    }

    if (source.startsWith('<!--', open)) {
      const end = source.indexOf('-->', open + 4);
      cursor = end === -1 ? source.length : end + 3;
      continue;
    }
    if (source.startsWith('<![CDATA[', open)) {
      const end = source.indexOf(']]>', open + 9);
      const body = source.slice(open + 9, end === -1 ? source.length : end);
      if (stack.length) stack[stack.length - 1].text += body;
      cursor = end === -1 ? source.length : end + 3;
      continue;
    }
    if (source.startsWith('<?', open) || source.startsWith('<!', open)) {
      const end = source.indexOf('>', open + 2);
      cursor = end === -1 ? source.length : end + 1;
      continue;
    }

    const close = source.indexOf('>', open + 1);
    if (close === -1) break;
    const body = source.slice(open + 1, close);

    if (body[0] === '/') {
      const name = localName(body.slice(1).trim());
      // Pop to the nearest matching open element. A mismatched close tag in a
      // machine-generated feed is corruption, and unwinding to the match keeps
      // the rest of the document readable instead of nesting everything after
      // it under the wrong parent.
      for (let i = stack.length - 1; i >= 0; i--) {
        if (stack[i].name === name) { stack.length = i; break; }
      }
      cursor = close + 1;
      continue;
    }

    const selfClosing = body.endsWith('/');
    const inner = selfClosing ? body.slice(0, -1) : body;
    const space = inner.search(/\s/);
    const name = localName(space === -1 ? inner : inner.slice(0, space));
    const element = new XmlElement(name, space === -1 ? {} : parseAttributes(inner.slice(space)));
    if (stack.length) stack[stack.length - 1].children.push(element);
    else if (!root) root = element;
    if (!selfClosing) stack.push(element);
    cursor = close + 1;
  }

  if (!root) throw new Error('XML document holds no root element');
  return root;
}

/**
 * First direct child with this local name.
 * @param {XmlElement|null|undefined} element
 * @param {string} name
 * @returns {XmlElement|null}
 */
export function child(element, name) {
  const children = element?.children;
  if (!children) return null;
  for (let i = 0; i < children.length; i++) {
    if (children[i].name === name) return children[i];
  }
  return null;
}

/**
 * Follow a chain of direct-child names.
 * @param {XmlElement|null|undefined} element
 * @param {...string} names
 * @returns {XmlElement|null}
 */
export function descend(element, ...names) {
  let node = element || null;
  for (const name of names) {
    node = child(node, name);
    if (!node) return null;
  }
  return node;
}

/**
 * Every descendant with this local name, in document order.
 * @param {XmlElement|null|undefined} element
 * @param {string} name
 * @returns {XmlElement[]}
 */
export function findAll(element, name) {
  const found = [];
  const walk = (node) => {
    for (const candidate of node.children) {
      if (candidate.name === name) found.push(candidate);
      walk(candidate);
    }
  };
  if (element) walk(element);
  return found;
}

/** Trimmed text of a descended element, or null. */
function textAt(element, ...names) {
  const node = descend(element, ...names);
  const value = node ? node.text.trim() : '';
  return value || null;
}

/** Finite number from a descended element, or null. */
function numberAt(element, ...names) {
  const raw = textAt(element, ...names);
  if (raw === null) return null;
  const value = Number(raw);
  return Number.isFinite(value) ? value : null;
}

/** Epoch ms from an ISO-8601 stamp, or null. Never `Invalid Date`. */
export function parseTimestampMs(raw) {
  const text = String(raw ?? '').trim();
  if (!text) return null;
  const ms = Date.parse(text);
  return Number.isFinite(ms) ? ms : null;
}

// ---------------------------------------------------------------------------
// Lambert-93 (EPSG:2154) inverse
// ---------------------------------------------------------------------------

/**
 * The QTV referential publishes station geometry in **projected metres**, not
 * degrees. These are the IGN NT/G-71 constants for RGF93 / Lambert-93 (GRS80,
 * standard parallels 44N/49N, origin 46.5N 3E, false easting/northing
 * 700000/6600000) — the same set `scripts/grid-audit/lib.mjs` uses to read
 * RTE's projected shapefiles. It is duplicated rather than imported because
 * that file is a measuring instrument that is never bundled, and a shipped
 * layer must not depend on one.
 */
const L93 = Object.freeze({
  n: 0.725_607_765_053_267,
  C: 11_754_255.426_096,
  Xs: 700_000.0,
  Ys: 12_655_612.049_876,
  e: 0.081_819_191_06,
  lambdaC: (3 * Math.PI) / 180,
});

/**
 * Invert the isometric latitude (IGN ALG0002). Converges to well under a
 * millimetre in a handful of turns at French latitudes; the iteration cap is a
 * backstop, not the exit condition.
 * @param {number} L Isometric latitude.
 * @param {number} e First eccentricity.
 * @returns {number} Geodetic latitude, radians.
 */
function latitudeFromIsometric(L, e) {
  const expL = Math.exp(L);
  let phi = 2 * Math.atan(expL) - Math.PI / 2;
  for (let i = 0; i < 32; i += 1) {
    const s = e * Math.sin(phi);
    const next = 2 * Math.atan(((1 + s) / (1 - s)) ** (e / 2) * expL) - Math.PI / 2;
    if (Math.abs(next - phi) < 1e-13) return next;
    phi = next;
  }
  return phi;
}

/**
 * The projection's own domain, in metres, covering metropolitan France with
 * generous slack. A referential row outside it is a typo or a placeholder, and
 * converting it would produce a plausible-looking coordinate in the Atlantic —
 * far worse than no coordinate at all.
 */
const L93_BOUNDS = Object.freeze({ minX: 90_000, maxX: 1_310_000, minY: 6_000_000, maxY: 7_200_000 });

/**
 * Lambert-93 easting/northing → `[longitude, latitude]` in degrees (WGS84;
 * RGF93 and WGS84 agree to well under a metre, far below the ~1 km stations
 * this positions).
 * @param {unknown} rawX Easting, metres.
 * @param {unknown} rawY Northing, metres.
 * @returns {[number, number]|null} Null when either ordinate is unusable.
 */
export function l93ToWgs84(rawX, rawY) {
  const x = Number(rawX);
  const y = Number(rawY);
  if (!Number.isFinite(x) || !Number.isFinite(y)) return null;
  if (x < L93_BOUNDS.minX || x > L93_BOUNDS.maxX) return null;
  if (y < L93_BOUNDS.minY || y > L93_BOUNDS.maxY) return null;
  const dx = x - L93.Xs;
  const dy = y - L93.Ys;
  const R = Math.hypot(dx, dy);
  const gamma = Math.atan2(dx, -dy);
  const lambda = L93.lambdaC + gamma / L93.n;
  const L = -(1 / L93.n) * Math.log(R / L93.C);
  const phi = latitudeFromIsometric(L, L93.e);
  return [(lambda * 180) / Math.PI, (phi * 180) / Math.PI];
}

