/**
 * The referential's published header, in publication order.
 *
 * The file is broken in a specific, stable way: the header declares 20 columns
 * and every data row carries 19. Measured 2026-08-31 — 1,206 of 1,206 rows.
 * The missing one is `code_insee_commune`, which is verifiable rather than
 * assumed: with it dropped, `axe` holds `A28`/`N0165`, `sens_cardinal` holds
 * `NORD_SUD`, and `x_deb`/`y_deb` hold Lambert-93 metres in range — and with it
 * kept, every one of those lands one column to the left and the coordinates
 * parse as road names.
 *
 * So the parser binds the header it was GIVEN when the counts agree, and falls
 * back to this repaired header when they are off by exactly that column. Any
 * other width is refused: a silently misaligned referential would place real
 * stations at plausible wrong coordinates, which is the one failure a map
 * cannot show you.
 */
export const QTV_REFERENTIAL_COLUMNS = Object.freeze([
  'code_pme', 'source', 'source_2', 'code_insee_commune', 'axe',
  'pr_debut', 'abscisse_debut', 'pr_fin', 'abscisse_fin',
  'sens_gestionnaire', 'sens_cardinal', 'sens_migratoire', 'sens_giratoire',
  'longueur', 'nb_voies', 'x_deb', 'y_deb', 'x_fin', 'y_fin', 'code_traficolor',
]);

/** The column the published rows omit. */
export const QTV_MISSING_COLUMN = 'code_insee_commune';

/**
 * Parse `refDir.csv` into station referential rows.
 *
 * @param {string} csv Raw semicolon-separated referential.
 * @returns {{stations:Map<string,object>, counts:object}}
 */
export function parseQtvReferential(csv) {
  const lines = String(csv ?? '').split(/\r?\n/).filter((line) => line.trim());
  const stations = new Map();
  const counts = { rows: 0, positioned: 0, halfPositioned: 0, unpositioned: 0, malformed: 0, duplicates: 0 };
  if (!lines.length) return { stations, counts };

  const header = lines[0].split(';').map((name) => name.trim());
  const repaired = header.filter((name) => name !== QTV_MISSING_COLUMN);

  for (let i = 1; i < lines.length; i++) {
    const fields = lines[i].split(';');
    let columns = null;
    if (fields.length === header.length) columns = header;
    else if (fields.length === repaired.length) columns = repaired;
    if (!columns) { counts.malformed += 1; continue; }

    const row = {};
    for (let c = 0; c < columns.length; c++) row[columns[c]] = (fields[c] ?? '').trim();
    const id = row.code_pme;
    if (!id) { counts.malformed += 1; continue; }
    if (stations.has(id)) { counts.duplicates += 1; continue; }
    counts.rows += 1;

    const from = l93ToWgs84(row.x_deb, row.y_deb);
    const to = l93ToWgs84(row.x_fin, row.y_fin);
    if (from && to) counts.positioned += 1;
    else if (from || to) counts.halfPositioned += 1;
    else counts.unpositioned += 1;

    const length = Number(row.longueur);
    const lanes = Number(row.nb_voies);
    stations.set(id, {
      id,
      // `DIRNO`, `DIRCE`, … — the operating DIR, spelled as the referential does.
      dir: row.source || null,
      road: row.axe || null,
      // The referential publishes `0` for "not stated", not for a road with no
      // lanes. 922 of 1,206 rows say 0, so reading it as a count would report
      // three quarters of the national network as laneless.
      lanes: Number.isFinite(lanes) && lanes > 0 ? lanes : null,
      direction: row.sens_cardinal || null,
      ring: row.sens_giratoire || null,
      length: Number.isFinite(length) && length > 0 ? length : null,
      marker: row.pr_debut || null,
      from: from ? [roundCoordinate(from[0]), roundCoordinate(from[1])] : null,
      to: to ? [roundCoordinate(to[0]), roundCoordinate(to[1])] : null,
    });
  }
  return { stations, counts };
}

/**
 * Speeds at or above this are not measurements.
 *
 * The 2026-08-31 snapshot topped out at 149 km/h, but the feed is documented —
 * and was observed during the same survey — to publish a `9999999` sentinel
 * where a station has no reading. A sentinel that reaches a colour scale paints
 * a free-flowing motorway; a bound this far above any French speed limit
 * cannot reject a real reading.
 */
export const QTV_SPEED_CEILING_KMH = 300;

/** Flow ceiling, vehicles/hour. The busiest station measured 17,486. */
export const QTV_FLOW_CEILING_VEH_H = 30_000;

/**
 * Read one `<basicData>` measurement into a validated value.
 *
 * `numberOfInputValuesUsed` is the field that makes this honest, and it is easy
 * to miss: 206 of the 2,412 values in the 2026-08-31 snapshot were computed
 * from ZERO samples and published as `0`. A zero built from no samples is "no
 * vehicle was measured", not "traffic has stopped" — and drawn on a speed
 * scale those two are opposite readings of the same road. Zero samples ⇒ null.
 *
 * @param {XmlElement} holder Element carrying the value and the sample count.
 * @param {string} valueElement Leaf holding the number.
 * @param {number} ceiling Sentinel bound.
 * @returns {{value:number|null, samples:number|null}}
 */
function readMeasurement(holder, valueElement, ceiling) {
  if (!holder) return { value: null, samples: null };
  const rawSamples = Number(holder.attrs.numberOfInputValuesUsed);
  const samples = Number.isFinite(rawSamples) ? rawSamples : null;
  const value = numberAt(holder, valueElement);
  if (value === null || value < 0 || value >= ceiling) return { value: null, samples };
  if (samples === 0) return { value: null, samples };
  return { value, samples };
}

/**
 * Project `qtvDir.xml` + `refDir.csv` into the compact measurements document.
 *
 * @param {string} xml Raw DATEX II `MeasuredDataPublication`.
 * @param {string} csv Raw station referential.
 * @param {object} [options]
 * @param {number} [options.nowMs] Reference instant for measurement age.
 * @returns {{publishedAt:string|null, publishedAtMs:number|null,
 *   measuredAtMs:number|null, ageMs:number|null, stations:object[], counts:object}}
 */
export function projectRoadSensors(xml, csv, { nowMs = Date.now() } = {}) {
  const { stations: referential, counts: referentialCounts } = parseQtvReferential(csv);
  const root = parseXml(xml);
  const publication = findAll(root, 'payloadPublication')[0] || root;
  const publishedAt = textAt(publication, 'publicationTime');
  const publishedAtMs = parseTimestampMs(publishedAt);

  const stations = [];
  const counts = {
    published: 0, positioned: 0, unmatched: 0,
    speeds: 0, flows: 0, stopped: 0, silent: 0,
    referential: referentialCounts,
  };
  let measuredAtMs = null;

  for (const site of findAll(publication, 'siteMeasurements')) {
    const id = String(child(site, 'measurementSiteReference')?.attrs.id || '').trim();
    if (!id) continue;
    counts.published += 1;

    const measuredAt = parseTimestampMs(textAt(site, 'measurementTimeDefault'));
    if (measuredAt !== null && (measuredAtMs === null || measuredAt > measuredAtMs)) {
      measuredAtMs = measuredAt;
    }

    let speed = { value: null, samples: null };
    let flow = { value: null, samples: null };
    for (const basic of findAll(site, 'basicData')) {
      const kind = localName(String(basic.attrs.type || ''));
      if (kind === 'TrafficSpeed') {
        speed = readMeasurement(child(basic, 'averageVehicleSpeed'), 'speed', QTV_SPEED_CEILING_KMH);
      } else if (kind === 'TrafficFlow') {
        flow = readMeasurement(
          descend(basic, 'vehicleFlow'), 'vehicleFlowRate', QTV_FLOW_CEILING_VEH_H,
        );
      }
    }

    const reference = referential.get(id) || null;
    if (!reference) counts.unmatched += 1;
    if (speed.value !== null) counts.speeds += 1;
    if (flow.value !== null) counts.flows += 1;
    // The two readings that only mean something TOGETHER: vehicles measured but
    // not moving is a jam; nothing measured at all is an empty road at 04:00.
    if (speed.value === 0 && flow.value !== null && flow.value > 0) counts.stopped += 1;
    if (speed.value === 0 && flow.value === 0) counts.silent += 1;

    // A station with no geometry cannot be drawn, and 364 of the 1,206 have
    // none. They are COUNTED, never served: shipping a third of the payload as
    // records the globe can only discard is waste, and reporting the published
    // total beside the positioned one is what keeps that honest on the row.
    if (!reference?.from) continue;
    counts.positioned += 1;

    stations.push({
      id,
      dir: reference?.dir ?? null,
      road: reference?.road ?? null,
      lanes: reference?.lanes ?? null,
      direction: reference?.direction ?? null,
      length: reference?.length ?? null,
      marker: reference?.marker ?? null,
      from: reference?.from ?? null,
      to: reference?.to ?? null,
      speed: speed.value,
      speedSamples: speed.samples,
      flow: flow.value,
      flowSamples: flow.samples,
      measuredAt,
    });
  }

  stations.sort((a, b) => a.id.localeCompare(b.id));

  return {
    publishedAt,
    publishedAtMs,
    measuredAtMs,
    // How old the newest reading already is when the projection runs. Published
    // because the layer's honest headline is not the speed, it is the speed's
    // age: measured 2026-08-31, a QTV file lands ~11 minutes after the
    // publication instant it carries.
    ageMs: measuredAtMs === null ? null : Math.max(0, nowMs - measuredAtMs),
    stations,
    counts,
  };
}
